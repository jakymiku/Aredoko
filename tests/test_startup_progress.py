class StartupProgressTests(unittest.TestCase):
    setUp = fixtures.ParallelReleaseTests.setUp

    def snapshot_files(self):
        return {p.relative_to(self.root).as_posix(): (p.read_bytes(), p.stat().st_mtime_ns)
                for p in self.root.rglob('*') if p.is_file()}

    def test_counts_are_completed_hashes_and_stages_are_not_app_ready(self):
        events = [];control = StartupProgress(events.append)
        before = self.snapshot_files()
        self.assertEqual(runtime.verify_release(self.root, progress=control), self.manifest)
        self.assertEqual(self.snapshot_files(), before)
        self.assertEqual([e['stage'] for e in events if e['state'] == 'complete'],
                         ['manifest', 'file_hashes', 'inventory'])
        hashes = [e for e in events if e['stage'] == 'file_hashes']
        self.assertEqual(hashes[0]['completed_files'], 0)
        self.assertEqual(hashes[-1]['completed_files'], len(self.manifest['entries']))
        self.assertEqual(hashes[-1]['completed_bytes'], self.manifest['total_bytes'])
        self.assertEqual([e['completed_files'] for e in hashes], sorted(e['completed_files'] for e in hashes))
        self.assertTrue(all(e['total_files'] is None for e in events if e['stage'] != 'file_hashes'))
        serialized = json.dumps(events)
        for forbidden in ('ready', 'percent', 'remaining', str(self.root), 'Aredoko.WinUI.exe'):
            self.assertNotIn(forbidden, serialized)

    def test_progress_does_not_skip_any_hash_or_lexical_path_guard(self):
        original_path = runtime.plain_path;original_digest = runtime.digest
        counts = Counter();hashes = Counter();lock = threading.Lock()
        def guarded(path, **kwargs):
            with lock:counts[(str(path), kwargs.get('directory', False))] += 1
            return original_path(path, **kwargs)
        def digest(path, **kwargs):
            with lock:hashes[path] += 1
            return original_digest(path, **kwargs)
        with patch.object(runtime, 'plain_path', guarded), patch.object(runtime, 'digest', digest):
            runtime.verify_release(self.root)
            expected = counts.copy();counts.clear();hashes.clear()
            runtime.verify_release(self.root, progress=StartupProgress())
        self.assertEqual(counts, expected)
        self.assertEqual(hashes, Counter({self.root / e['path']: 1 for e in self.manifest['entries']}))

    def test_completed_hash_count_does_not_hide_failed_inventory(self):
        (self.root / 'unlisted-cache').write_bytes(b'generated only')
        events = [];control = StartupProgress(events.append)
        with self.assertRaisesRegex(ValueError, 'Unlisted'):
            runtime.verify_release(self.root, progress=control)
        self.assertEqual(events[-1]['stage'], 'inventory')
        self.assertEqual(events[-1]['state'], 'failed')
        self.assertTrue(any(e['stage'] == 'file_hashes' and e['state'] == 'complete' for e in events))

    def test_corruption_never_reports_hash_stage_complete(self):
        (self.root / 'bin/Aredoko.WinUI.exe').write_bytes(b'changed generated bytes')
        events = []
        with self.assertRaisesRegex(ValueError, 'file changed'):
            runtime.verify_release(self.root, progress=StartupProgress(events.append))
        self.assertEqual(events[-1]['state'], 'failed')
        self.assertEqual(events[-1]['stage'], 'file_hashes')
        self.assertFalse(any(e['stage'] == 'file_hashes' and e['state'] == 'complete' for e in events))

    def test_cancel_before_start_reads_no_payload(self):
        control = StartupProgress();control.cancel()
        with patch.object(runtime, 'plain_path') as guard, self.assertRaises(StartupCancelled):
            runtime.verify_release(self.root, progress=control)
        guard.assert_not_called()

    def test_cancel_at_hash_start_dispatches_no_hash_and_keeps_payload(self):
        events = [];before = self.snapshot_files()
        def sink(value):
            events.append(value)
            if value['stage'] == 'file_hashes':control.cancel()
        control = StartupProgress(sink)
        with patch.object(runtime, 'digest') as hashed, self.assertRaises(StartupCancelled):
            runtime.verify_release(self.root, progress=control)
        hashed.assert_not_called()
        self.assertEqual(control.snapshot['state'], 'cancelled')
        self.assertEqual(control.snapshot['completed_files'], 0)
        self.assertEqual(self.snapshot_files(), before)

    def test_cancel_during_hash_stops_reading_at_block_boundary(self):
        control = StartupProgress()
        class Source(io.BytesIO):
            reads = 0
            def read(self, amount=-1):
                self.reads += 1
                value = super().read(amount)
                control.cancel()
                return value
        source = Source(b'x' * (3 * 1024 * 1024))
        with patch.object(Path, 'open', return_value=source), self.assertRaises(StartupCancelled):
            runtime.digest(self.root / 'generated-large-file', progress=control)
        self.assertEqual(source.reads, 1)

    def test_cancellation_inside_inventory_stops_directory_work(self):
        control = StartupProgress();original = runtime._checked_directory;calls = []
        def checked(path, **kwargs):
            calls.append(path);result = original(path, **kwargs);control.cancel();return result
        with patch.object(runtime, '_checked_directory', checked), self.assertRaises(StartupCancelled):
            list(runtime._parallel_tree(self.root, progress=control))
        self.assertEqual(calls, [self.root])

    def test_progress_is_throttled_and_completion_is_always_sent(self):
        now = [0.0];events = []
        control = StartupProgress(events.append, clock=lambda: now[0])
        with control.phase('file_hashes', files=500, bytes=500):
            for _ in range(499):control.advance(files=1, bytes=1)
            self.assertEqual(len(events), 1)
            now[0] = 0.11;control.advance(files=1, bytes=1)
        self.assertEqual(len(events), 3)
        self.assertEqual(events[-1]['state'], 'complete')
        self.assertEqual(events[-1]['completed_files'], 500)
        events[-1]['completed_files'] = -1
        self.assertEqual(control.snapshot['completed_files'], 500)

    def test_incomplete_totals_and_invalid_updates_do_not_become_success(self):
        for files, amount in ((2, 1), (1, 2), (1, -1)):
            control = StartupProgress()
            with self.subTest(files=files, amount=amount), self.assertRaises(ValueError):
                with control.phase('file_hashes', files=files):control.advance(files=amount)
            self.assertEqual(control.snapshot['state'], 'failed')

    def test_sink_failure_stops_verification_without_masking_original_error(self):
        control = StartupProgress(lambda _: (_ for _ in ()).throw(BrokenPipeError('generated sink closed')))
        with patch.object(runtime, 'digest') as hashed, self.assertRaises(BrokenPipeError):
            runtime.verify_release(self.root, progress=control)
        hashed.assert_not_called()
        self.assertEqual(control.snapshot['state'], 'failed')

    def test_runtime_probe_result_and_cancellation_do_not_touch_other_child(self):
        control = StartupProgress()
        result = launch._runtime_check([sys.executable, '-B', '-c', 'print("generated probe")'],
            root=self.root, timeout=5, progress=control, capture=True)
        self.assertEqual(result.returncode, 0)
        self.assertIn('generated probe', result.stdout)
        other = subprocess.Popen([sys.executable, '-B', '-c', 'import time;time.sleep(30)'])
        marker = self.root.parent / 'probe-started'
        children = [];original = subprocess.Popen
        def spawn(*args, **kwargs):
            child = original(*args, **kwargs);children.append(child);return child
        errors = []
        def check():
            try:
                launch._runtime_check([sys.executable, '-B', '-c',
                    'from pathlib import Path;import sys,time;Path(sys.argv[1]).touch();time.sleep(30)', str(marker)],
                    root=self.root, timeout=10, progress=control, capture=True)
            except Exception as error:errors.append(error)
        worker = threading.Thread(target=check)
        try:
            with patch.object(launch.subprocess, 'Popen', spawn):
                worker.start();deadline = time.monotonic() + 5
                while not marker.exists() and time.monotonic() < deadline:time.sleep(0.01)
                self.assertTrue(marker.exists());control.cancel();worker.join(timeout=5)
            self.assertFalse(worker.is_alive())
            self.assertEqual(len(errors), 1);self.assertIsInstance(errors[0], StartupCancelled)
            self.assertIsNotNone(children[0].poll());self.assertIsNone(other.poll())
            self.assertTrue(children[0].stdout.closed);self.assertTrue(children[0].stderr.closed)
        finally:
            control.cancel();worker.join(timeout=5)
            for child in children + [other]:
                if child.poll() is None:child.kill()
                child.wait(timeout=5)

    def test_probe_timeout_and_early_failure_are_bounded_and_reaped(self):
        result = launch._runtime_check([sys.executable, '-B', '-c', 'raise SystemExit(7)'],
            root=self.root, timeout=5, progress=StartupProgress())
        self.assertEqual(result.returncode, 7)
        children = [];original = subprocess.Popen
        def spawn(*args, **kwargs):
            child = original(*args, **kwargs);children.append(child);return child
        with patch.object(launch.subprocess, 'Popen', spawn), self.assertRaises(subprocess.TimeoutExpired):
            launch._runtime_check([sys.executable, '-B', '-c', 'import time;time.sleep(30)'],
                root=self.root, timeout=0.15, progress=StartupProgress(), capture=True)
        self.assertIsNotNone(children[0].poll())
        self.assertTrue(children[0].stdout.closed)

    def test_precancelled_probe_creates_no_process(self):
        control = StartupProgress();control.cancel()
        with patch.object(launch.subprocess, 'Popen') as spawn, self.assertRaises(StartupCancelled):
            launch._runtime_check(['must not run'], root=self.root, timeout=5, progress=control)
        spawn.assert_not_called()

    def test_preflight_stages_report_real_check_outcomes(self):
        from types import SimpleNamespace
        events = [];control = StartupProgress(events.append)
        manifest = {'python_bundled': True, 'media_tools_bundled': True, 'ai_runtime_bundled': True}
        def check(command, **kwargs):
            self.assertIs(kwargs['progress'], control)
            return subprocess.CompletedProcess(command, 0, '{"pass":true}', '')
        with patch.object(launch, 'verify_release', return_value=manifest), \
             patch.object(launch, 'python_layout') as python, patch.object(launch, 'media_layout') as media, \
             patch.object(launch, 'os', SimpleNamespace(name='nt')), patch.object(launch, '_runtime_check', side_effect=check) as probe:
            self.assertEqual(launch.preflight(self.root, progress=control), manifest)
        python.assert_called_once_with(self.root / 'runtime/python', True, progress=control)
        media.assert_called_once_with(self.root / 'runtime/media', progress=control)
        self.assertEqual(probe.call_count, 3)
        self.assertIn('-B', probe.call_args_list[0].args[0])
        self.assertEqual([e['stage'] for e in events if e['state'] == 'complete'],
                         ['runtime_layout', 'python_imports', 'media_probe'])
        self.assertTrue(all(e['total_files'] is None and e['total_bytes'] is None for e in events))

    def test_preflight_layout_failure_is_not_a_complete_stage(self):
        events = []
        with patch.object(launch, 'verify_release', return_value={}), \
             patch.object(launch, '_runtime_check') as probe, self.assertRaisesRegex(ValueError, 'bundled Python'):
            launch.preflight(self.root, progress=StartupProgress(events.append))
        self.assertEqual(events[-1]['stage'], 'runtime_layout')
        self.assertEqual(events[-1]['state'], 'failed')
        probe.assert_not_called()


