"""Generated receipt boundaries; never executes selected Python/model code."""
import hashlib,json
from pathlib import Path
import sys,tempfile,unittest
from unittest.mock import patch
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'app'))
import managed_ai_runtime as managed
from ai_runtime import REQUIRED_MODULES,MARKER,inspect_runtime
from ai_profiles import DEFAULT_PROFILE

class ManagedRuntimeTests(unittest.TestCase):
    def setUp(self):
        temp=tempfile.TemporaryDirectory();self.addCleanup(temp.cleanup)
        self.base=Path(temp.name);self.root=self.base/'runtime';self.root.mkdir()
        self.home=self.base/'python';self.home.mkdir()
        self.package=self.base/'python.nupkg';self.package.write_bytes(b'generated fixture')
        self.cache=self.base/'wheels';self.cache.mkdir()
        paths={'Scripts/python.exe','Scripts/pythonw.exe','pyvenv.cfg',*(f'Lib/site-packages/{name}/__init__.py' for name in REQUIRED_MODULES)}
        entries=[]
        for name in sorted(paths):
            path=self.root/name;path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(b'generated fixture')
            entries.append({'path':name,'bytes':len(path.read_bytes()),'sha256':hashlib.sha256(path.read_bytes()).hexdigest()})
        self.value={'format':managed.FORMAT,'recipe_sha256':managed.RECIPE_SHA256,
                    'home':str(self.home),'base_package':str(self.package),'wheel_cache':str(self.cache),
                    'probe':{'profile':DEFAULT_PROFILE.key,'device':'cpu'},
                    'abi':{'python':'3.13','architecture':'x64','engine':'pytorch','compute':'cuda','torch':'2.9.1+cu128','cuda':'12.8','modules':list(REQUIRED_MODULES)},
                    'entries':entries,'files_count':len(entries),'total_bytes':sum(entry['bytes'] for entry in entries)}
        self.addCleanup(patch.stopall)
        patch.object(managed,'recipe',return_value={'entries':[]}).start()
        patch.object(managed,'verify_base').start();patch.object(managed,'verify_binding').start()
        self.checksum=self.write()

    def write(self):
        raw=json.dumps(self.value).encode();(self.root/MARKER).write_bytes(raw)
        return hashlib.sha256(raw).hexdigest()

    def test_selected_receipt_verifies_without_wheel_cache(self):
        self.cache.rmdir()
        info=inspect_runtime(self.root,verify=True,expected=self.checksum)
        self.assertEqual(info['python'],str(self.root/'Scripts/python.exe'))
        self.assertFalse(info['cache_required'])

    def test_new_selection_cannot_trust_an_unanchored_receipt(self):
        self.cache.rmdir()
        with self.assertRaisesRegex(ValueError,'Original wheel cache'):
            inspect_runtime(self.root,verify=True)

    def test_corruption_and_unlisted_bytecode_are_rejected(self):
        path=self.root/'Lib/site-packages/torch/__init__.py'
        original=path.read_bytes();path.write_bytes(b'changed')
        with self.assertRaisesRegex(ValueError,'runtime changed'):
            inspect_runtime(self.root,verify=True,expected=self.checksum)
        path.write_bytes(original)
        extra=path.parent/'__pycache__/injected.pyc';extra.parent.mkdir();extra.write_bytes(b'generated bytecode')
        with self.assertRaisesRegex(ValueError,'Unlisted'):
            inspect_runtime(self.root,verify=True,expected=self.checksum)

    def test_changed_receipt_or_malformed_types_are_rejected(self):
        self.value['probe']['device']='cuda';self.write()
        with self.assertRaisesRegex(ValueError,'inventory changed'):
            inspect_runtime(self.root,expected=self.checksum)
        self.value['entries'][0]['sha256']=False;self.write()
        with self.assertRaises(ValueError):inspect_runtime(self.root)

    def test_forged_generated_dll_is_not_accepted_on_first_selection(self):
        path=self.root/'Scripts/injected.dll';path.write_bytes(b'injected')
        self.value['entries'].append({'path':'Scripts/injected.dll','bytes':8,'sha256':hashlib.sha256(b'injected').hexdigest()})
        self.value['files_count']+=1;self.value['total_bytes']+=8;self.write()
        def original(root,cache,lock,**kwargs):
            kwargs['inventory'].extend(entry for entry in self.value['entries'] if entry['path'].startswith('Lib/'))
        with patch.object(managed,'verify_wheels',side_effect=original):
            with self.assertRaisesRegex(ValueError,'generated runtime file'):
                inspect_runtime(self.root,verify=True)

if __name__=='__main__':unittest.main()
