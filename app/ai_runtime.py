"""Local opt-in AI runtime inventory. No imports of selected code/models/network.

The inventory proves consistency with a user-selected pack, not publisher trust.
Downloaded packs additionally require a trusted catalog (acquisition layer).
"""
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import stat
import struct
from storage_lease import plain_path

FORMAT = 'aredoko-ai-runtime-v1'
MARKER = 'aredoko-ai-runtime.json'
LIMIT = 32 * 1024**2
REQUIRED_MODULES = ('torch', 'transformers', 'sentence_transformers', 'numpy', 'PIL')
OPTIONAL_MODULES = ('onnxruntime', 'laya', 'tokenizers', 'safetensors')


def object_pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:raise ValueError('Duplicate runtime field')
        result[key] = value
    return result


def relative(value):
    if (not isinstance(value, str) or not value or len(value) > 1024
            or any(c in value for c in '\\:<>"|?*') or any(ord(c) < 32 for c in value)):
        raise ValueError('Invalid runtime inventory path')
    parts = value.split('/')
    if PurePosixPath(value).is_absolute() or any(
            p in ('', '.', '..') or p.endswith((' ', '.')) or p.split('.')[0].upper() in
            {'CON','PRN','AUX','NUL',*(f'COM{i}' for i in range(1,10)),*(f'LPT{i}' for i in range(1,10))}
            for p in parts):raise ValueError('Invalid runtime inventory path')
    return value


def digest(path, cancelled=lambda: False, on_bytes=None):
    if cancelled():raise RuntimeError('Runtime validation cancelled')
    result = hashlib.sha256()
    path=plain_path(path);before=path.stat()
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024*1024), b''):
            if cancelled():raise RuntimeError('Runtime validation cancelled')
            result.update(block)
            if on_bytes is not None:on_bytes(len(block))
    after=plain_path(path).stat()
    identity=lambda st:(st.st_dev,st.st_ino,st.st_size,st.st_mtime_ns,st.st_ctime_ns,st.st_nlink)
    if identity(before)!=identity(after):raise ValueError('Runtime file changed during validation')
    if cancelled():raise RuntimeError('Runtime validation cancelled')
    return result.hexdigest()


def files(root, cancelled=lambda: False):
    root=plain_path(root, directory=True)
    for path in sorted(root.iterdir()):
        if cancelled():raise RuntimeError('Runtime validation cancelled')
        directory=path.is_dir();plain_path(path, directory=directory)
        # Generated bytecode is not part of the sealed source inventory, but an
        # ignored cache directory must never hide a link/reparse traversal.
        if directory and path.name == '__pycache__':continue
        if directory:yield from files(path, cancelled)
        else:yield path


def validate_abi(value):
    if not isinstance(value,dict) or set(value)!={'python','architecture','engine','compute','torch','cuda','modules'}:
        raise ValueError('Invalid runtime ABI')
    if not isinstance(value['python'],str) or not re.fullmatch(r'3\.(1[1-9]|[2-9][0-9])',value['python']):
        raise ValueError('Python 3.11+ is required')
    if value['architecture']!='x64' or value['engine']!='pytorch' or value['compute'] not in ('cpu','cuda'):
        raise ValueError('Unsupported runtime ABI')
    if not isinstance(value['torch'],str) or not re.fullmatch(r'[0-9][0-9A-Za-z.+_-]{0,63}',value['torch']):
        raise ValueError('Invalid runtime version')
    if value['compute']=='cpu':
        if value['cuda'] is not None:raise ValueError('CPU runtime cannot declare CUDA')
    elif not isinstance(value['cuda'],str) or not re.fullmatch(r'[0-9]{1,2}\.[0-9]{1,2}',value['cuda']):
        raise ValueError('Invalid CUDA version')
    modules=value['modules']
    if (not isinstance(modules,list) or any(not isinstance(m,str) for m in modules)
            or len(modules)!=len(set(modules)) or not set(REQUIRED_MODULES)<=set(modules)
            or not set(modules)<=set(REQUIRED_MODULES+OPTIONAL_MODULES)):
        raise ValueError('Invalid runtime module contract')
    return value


def required_files(abi):
    stem='python'+abi['python'].replace('.','')
    return {'python.exe','pythonw.exe','LICENSE.txt',stem+'.dll',stem+'.zip',stem+'._pth',
            *(f'Lib/site-packages/{m}/__init__.py' for m in abi['modules'])}


def parse_inventory(raw, *, expected=None, cancelled=lambda: False):
    """Validate only bounded inventory data; no filesystem or selected code I/O."""
    if not isinstance(raw,bytes) or len(raw)>LIMIT:raise ValueError('Runtime inventory exceeds limit')
    checksum=hashlib.sha256(raw).hexdigest()
    if expected is not None and checksum!=expected:raise ValueError('Selected runtime inventory changed')
    value=json.loads(raw.decode('utf-8'),object_pairs_hook=object_pairs)
    if not isinstance(value,dict) or set(value)!={'format','abi','entries','files_count','total_bytes'} or value['format']!=FORMAT:
        raise ValueError('Unsupported runtime inventory')
    abi=validate_abi(value['abi'])
    entries=value['entries']
    if not isinstance(entries,list) or not 1<=len(entries)<=100000:raise ValueError('Invalid runtime inventory')
    names=set();folded=set();total=0;by_name={}
    for entry in entries:
        if cancelled():raise RuntimeError('Runtime validation cancelled')
        if not isinstance(entry,dict) or set(entry)!={'path','bytes','sha256'}:raise ValueError('Invalid runtime entry')
        name=relative(entry['path'])
        if name.casefold() in folded or name.casefold()==MARKER:raise ValueError('Duplicate runtime path')
        folded.add(name.casefold());names.add(name);by_name[name]=entry
        if (type(entry['bytes']) is not int or entry['bytes']<0 or not isinstance(entry['sha256'],str)
                or not re.fullmatch('[0-9a-f]{64}',entry['sha256'])):raise ValueError('Invalid runtime digest')
        total+=entry['bytes']
        if total>64*1024**3:raise ValueError('Runtime exceeds limit')
    if (not required_files(abi)<=names or type(value['files_count']) is not int or value['files_count']!=len(entries)
            or type(value['total_bytes']) is not int or value['total_bytes']!=total):
        raise ValueError('Runtime inventory is incomplete')
    return value,abi,by_name,checksum


def inspect_runtime(root, *, verify=False, expected=None, cancelled=lambda: False, progress=None):
    root=plain_path(root,directory=True)
    marker=plain_path(root/MARKER)
    if marker.stat().st_size>LIMIT:raise ValueError('Runtime inventory exceeds limit')
    with marker.open('rb') as stream:raw=stream.read(LIMIT+1)
    if len(raw)>LIMIT:raise ValueError('Runtime inventory exceeds limit')
    value,abi,by_name,checksum=parse_inventory(raw,expected=expected,cancelled=cancelled)
    entries=value['entries'];names=set(by_name);total=value['total_bytes']
    # A small ordinary-startup inspection checks executable/core paths only.
    # Full byte/inventory validation occurs on selection and before worker launch.
    for name in required_files(abi):plain_path(root/name)
    python=plain_path(root/'python.exe')
    with python.open('rb') as stream:header=stream.read(4096)
    if len(header)<64 or header[:2]!=b'MZ':raise ValueError('Expected an x64 Python executable')
    offset=struct.unpack_from('<I',header,60)[0]
    if offset>len(header)-24 or header[offset:offset+4]!=b'PE\0\0' or struct.unpack_from('<H',header,offset+4)[0]!=0x8664:
        raise ValueError('Expected an x64 Python executable')
    stem='python'+abi['python'].replace('.','')
    pth=root/(stem+'._pth')
    if pth.stat().st_size>4096:raise ValueError('Runtime module paths exceed limit')
    lines=[line.strip() for line in pth.read_text(encoding='utf-8-sig').splitlines() if line.strip() and not line.startswith('#')]
    if lines!=[stem+'.zip','.','DLLs','Lib/site-packages','import site']:
        raise ValueError('Runtime module paths must stay inside the selected pack')
    for name in ('python.exe',stem+'._pth'):
        entry=by_name[name]
        if (root/name).stat().st_size!=entry['bytes'] or digest(root/name,cancelled)!=entry['sha256']:
            raise ValueError('Runtime core file changed')
    if verify:
        if {p.relative_to(root).as_posix() for p in files(root,cancelled)}!=names|{MARKER}:
            raise ValueError('Unlisted or missing runtime files')
        counts={'stage':'checking_runtime','files_done':0,'files_total':len(entries),'bytes_done':0,'bytes_total':total}
        def report(amount=0):
            counts['bytes_done']+=amount
            if progress is not None:progress(dict(counts))
        report()
        def validate(entry,stopped,on_chunk):
            path=plain_path(root/entry['path'])
            if path.stat().st_size!=entry['bytes'] or digest(path,stopped,on_chunk)!=entry['sha256']:
                raise ValueError('Runtime file changed')
        def file_done():
            counts['files_done']+=1;report()
        from runtime_verification import verify_entries
        verify_entries(entries,validate,cancelled,report,file_done)
    if verify and digest(marker,cancelled)!=checksum:raise ValueError('Runtime inventory changed during validation')
    return {'root':str(root),'python':str(python),'manifest_sha256':checksum,'abi':abi,
            'files':len(entries),'bytes':total,'verification':'full' if verify else 'core_only',
            'model_loaded':False,'driver_tested':False}


def model_state(profile, repo, models_root):
    if profile is None:return {'state':'model_profile_invalid','ready':False}
    try:
        directory=profile.model_path(repo,models_root=models_root)
        if not directory.exists():return {'state':'model_missing','ready':False}
        plain_path(directory,directory=True)
        marker=directory/'aredoko-revision.txt'
        if not marker.exists():return {'state':'model_revision_missing','ready':False}
        plain_path(marker)
        if marker.stat().st_size>256 or marker.read_text(encoding='utf-8').strip()!=profile.revision:
            return {'state':'model_revision_mismatch','ready':False}
        config=directory/'config.json'
        if not config.exists():return {'state':'model_files_missing','ready':False}
        plain_path(config)
        weights=[directory/'model.safetensors',directory/'pytorch_model.bin']
        present=any(p.exists() and plain_path(p).stat().st_size>0 for p in weights)
        index=directory/'model.safetensors.index.json'
        if not present and index.exists():
            plain_path(index)
            if index.stat().st_size>1024**2:raise ValueError('Model index exceeds limit')
            value=json.loads(index.read_text(encoding='utf-8'),object_pairs_hook=object_pairs)
            mapping=value.get('weight_map') if isinstance(value,dict) else None
            if not isinstance(mapping,dict) or not mapping:raise ValueError('Invalid model index')
            shards={relative(name) for name in mapping.values()}
            present=all(plain_path(directory/name).stat().st_size>0 for name in shards)
        if not present:return {'state':'model_files_missing','ready':False}
        if not any(p.exists() and plain_path(p).stat().st_size>0 for p in (directory/'tokenizer.json',directory/'tokenizer.model')):
            return {'state':'model_files_missing','ready':False}
        return {'state':'model_files_present','ready':True,'revision':profile.revision,'model_loaded':False}
    except (ValueError,OSError,UnicodeError):return {'state':'model_invalid','ready':False}


def legacy_runtime_state(python):
    if python is None:return 'runtime_missing'
    try:
        path=plain_path(python)
        directory=path.parent.parent if path.parent.name.lower()=='scripts' else path.parent
        for name in REQUIRED_MODULES:
            module=directory/'Lib/site-packages'/name/'__init__.py'
            if not module.exists():return 'ai_libraries_missing'
            plain_path(module)
        return 'legacy_runtime_unverified'
    except FileNotFoundError:return 'runtime_missing'
    except (ValueError,OSError):
        return 'runtime_missing' if not Path(python).exists() else 'runtime_invalid'
